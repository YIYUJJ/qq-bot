/** 自检：id 唯一、每道题的目标都在记忆池里、每条目标记忆都有题 */
export function validateTestset() {
  const ids = MEMORIES.map((m) => m.id)
  const problems = []
  if (new Set(ids).size !== ids.length) problems.push('记忆 id 有重复')
  for (const q of QUESTIONS) if (!ids.includes(q.target)) problems.push('题目指向不存在的记忆：' + q.q)
  for (const [id] of TARGETS) if (!QUESTIONS.some((q) => q.target === id)) problems.push('目标记忆没有题：' + id)
  const qs = QUESTIONS.map((x) => x.q)
  if (new Set(qs).size !== qs.length) problems.push('题目有重复')
  return problems
}
